#!/usr/bin/env python3
"""Build the game's static data tables from the YAML files in data/.

Usage:
    datagen.py OUTDIR       write partids.h and parts_tables.c into OUTDIR

Each YAML file is a list of entries, one per element of a C array. An entry
is written out as a C designated initializer: its keys are the struct's
field names and its values are C values.

    - name: iengineFuelMizer        # its enum value in partids.h
      szName: "Fuel Mizer"          # sz keys are strings (Windows-1252)
      rgwtOreCost: [8]              # lists become {8}
      grfAbilities: engineFuelMizer # other strings are C expressions
      hul: {...}                    # maps become nested initializers

The compiler checks the field names, enum values and types, so this script
knows nothing of the structs. Fields left out are zero. Only keys starting
with f may hold true/false, and a string too long for its sz field fails a
static assertion.

An entry's position in its file is its enum value. Code uses the names, but
saved ship designs store hull and part numbers, so entries are append-only:
reordering or removing one would load 2.6j and 2.8 designs with the wrong
parts. The regression's checkpoints hold such designs and would show it.
Code that uses a renamed entry's old name no longer compiles.

Fields the generator fills in, which the YAML must not set:
    id           COMPART tables: the position + 1
    hul.ihuldef  hulls: the hull's HulDef
    hul.chs      the number of hul.rghs slots
"""

import os
import re
import sys

try:
    import yaml
except ImportError:
    sys.stderr.write("datagen: the build needs PyYAML (python3 -m pip install pyyaml)\n")
    sys.exit(1)

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

GENERATED = "Generated by data/datagen.py from data/{}. Do not edit."

# (YAML file, C type, array, enum, count value, name prefix, what to derive)
# in the order the enums appear in partids.h. Starbase hulls continue HulDef
# after the ship hulls: each has an isbhull name and a HulDef name (huldef).
PARTS = [
    ("parts/hulls.yaml", "HULDEF", "rghuldef", "HulDef", None, "ihuldef", "hull"),
    ("parts/starting-starbases.yaml", "SHDEF", "rgshdefSBT", "StartingStarbase", None, "", None),
    ("parts/starting-ships.yaml", "SHDEF", "rgshdefT", "StartingShip", None, "", None),
    ("parts/starbase-hulls.yaml", "HULDEF", "rghuldefSB", "isbhull", "isbhullCount", "isbhull", "starbase hull"),
    ("parts/engines.yaml", "ENGINE", "rgengine", "iengine", "iengineCount", "iengine", "id"),
    ("parts/armor.yaml", "ARMOR", "rgarmor", "iarmor", "iarmorCount", "iarmor", "id"),
    ("parts/scanners.yaml", "SCANNER", "rgscanner", "iscanner", "iscannerCount", "iscanner", "id"),
    ("parts/shields.yaml", "SHIELD", "rgshield", "ishield", "ishieldCount", "ishield", "id"),
    ("parts/electrical.yaml", "SPECIAL", "rgspecialE", "ispecialE", "ispecialECount", "ispecialE", "id"),
    ("parts/mechanical.yaml", "SPECIAL", "rgspecialM", "ispecialM", "ispecialMCount", "ispecialM", "id"),
    ("parts/mine-layers.yaml", "MINES", "rgmines", "imines", "iminesCount", "imines", "id"),
    ("parts/mining-robots.yaml", "MINING", "rgmining", "imining", "iminingCount", "imining", "id"),
    ("parts/planetary.yaml", "PLANETARY", "rgplanetary", "iplanetary", "iplanetaryCount", "iplanetary", "id"),
    ("parts/terraformers.yaml", "TERRA", "rgterra", "iterra", "iterraCount", "iterra", "id"),
    ("parts/bombs.yaml", "BOMB", "rgbomb", "ibomb", "ibombCount", "ibomb", "id"),
    ("parts/torpedoes.yaml", "TORP", "rgtorp", "itorp", "itorpCount", "itorp", "id"),
    ("parts/beams.yaml", "BEAM", "rgbeam", "ibeam", "ibeamCount", "ibeam", "id"),
    ("parts/starbase-specials.yaml", "SPECIALSB", "rgspecialSB", "ispecialSB", "ispecialSBCount", "ispecialSB", "id"),
]

IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")
# A C value other than a number or string: names, |, +, -, shifts, parens.
EXPR = re.compile(r"[A-Za-z0-9_ |+\-<>()~]+\Z")


class DataError(Exception):
    pass


def CString(s, where):
    try:
        raw = s.encode("cp1252")
    except UnicodeEncodeError:
        raise DataError("{}: {!r} is not Windows-1252".format(where, s))
    out = []
    for b in raw:
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append("\\{:03o}".format(b))
    return '"' + "".join(out) + '"'


def CValue(key, value, where, asserts, path):
    """Return the C initializer for one YAML value."""
    if isinstance(value, bool):
        if not key.startswith("f"):
            raise DataError("{}: {} is true/false; only f keys are flags (quote a name like 'no')".format(where, key))
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        if key.startswith("sz"):
            lit = CString(value, where)
            asserts.append('_Static_assert(sizeof({0}) <= sizeof({1}), "{1} is too long");'.format(lit, path))
            return lit
        if not EXPR.match(value):
            raise DataError("{}: {}: {!r} is not a C value".format(where, key, value))
        return value
    if key.startswith("sz"):
        raise DataError("{}: {} must be a string".format(where, key))
    if isinstance(value, list):
        items = [CValue(key, v, where, asserts, "{}[{}]".format(path, i)) for i, v in enumerate(value)]
        return "{" + ", ".join(items) + "}"
    if isinstance(value, dict):
        return CStruct(value, where, asserts, path)
    raise DataError("{}: {}: unsupported value {!r}".format(where, key, value))


def CStruct(fields, where, asserts, path, indent=None):
    items = []
    for key, value in fields.items():
        if not isinstance(key, str) or not IDENT.match(key):
            raise DataError("{}: {!r} is not a field name".format(where, key))
        items.append(".{} = {}".format(key, CValue(key, value, where, asserts, "{}.{}".format(path, key))))
    if indent is None:
        return "{" + ", ".join(items) + "}"
    return "{\n" + "".join("{}{},\n".format(indent, item) for item in items) + indent[:-4] + "}"


def LoadParts(file, prefix, derive):
    path = os.path.join(HERE, file)
    with open(path, encoding="utf-8") as f:
        entries = yaml.safe_load(f)
    if not isinstance(entries, list) or not entries:
        raise DataError("data/{}: expected a list of entries".format(file))
    for i, entry in enumerate(entries):
        where = "data/{}: entry {}".format(file, i)
        if not isinstance(entry, dict):
            raise DataError("{}: expected a map".format(where))
        name = entry.get("name")
        if not isinstance(name, str) or not IDENT.match(name) or not name.startswith(prefix):
            raise DataError("{}: name {!r} must be a C name starting with {!r}".format(where, name, prefix))
        for key in ("id",) if derive == "id" else ():
            if key in entry:
                raise DataError("{}: {} is generated from the position; remove it".format(where, key))
        hul = entry.get("hul")
        if isinstance(hul, dict):
            for key in ("chs",) + (("ihuldef",) if derive in ("hull", "starbase hull") else ()):
                if key in hul:
                    raise DataError("{}: hul.{} is generated; remove it".format(where, key))
        if derive == "starbase hull" and not IDENT.match(str(entry.get("huldef", ""))):
            raise DataError("{}: starbase hulls need huldef, their HulDef name".format(where))
    return entries


def Generate(outdir):
    header = [
        "// " + GENERATED.format("parts/*.yaml"),
        "// The part, hull and starting design indexes, included by enums.h.",
        "#ifndef STARS_PARTIDS_H",
        "#define STARS_PARTIDS_H",
        "",
    ]
    body = ["// " + GENERATED.format("parts/*.yaml"), '#include "common.h"', ""]
    asserts = []
    tables = {}
    for file, ctype, array, enum, count, prefix, derive in PARTS:
        tables[array] = LoadParts(file, prefix, derive)
    rgHulDef = [e["name"] for e in tables["rghuldef"]] + [e["huldef"] for e in tables["rghuldefSB"]]
    for file, ctype, array, enum, count, prefix, derive in PARTS:
        entries = tables[array]
        names = rgHulDef if enum == "HulDef" else [e["name"] for e in entries]
        header.append("enum {} {{".format(enum))
        header += ["    {} = {},".format(name, i) for i, name in enumerate(names)]
        if count:
            header.append("    {} = {},".format(count, len(names)))
        header += ["};", ""]
        rgsz = []
        for i, entry in enumerate(entries):
            where = "data/{}: {}".format(file, entry["name"])
            fields = {k: v for k, v in entry.items() if k not in ("name", "huldef")}
            if derive == "id":
                fields = dict(id=i + 1, **fields)
            hul = fields.get("hul")
            if isinstance(hul, dict):
                hul = dict(hul)
                if derive == "hull":
                    hul = dict(ihuldef=entry["name"], **hul)
                elif derive == "starbase hull":
                    hul = dict(ihuldef=entry["huldef"], **hul)
                if "rghs" in hul:
                    hul["chs"] = len(hul["rghs"])
                fields["hul"] = hul
            rgsz.append("    /* {} */ {}".format(i, CStruct(fields, where, asserts, "{}[{}]".format(array, i), " " * 8)))
        body.append("{} {}[{}] = {{\n{}\n}};\n".format(ctype, array, len(entries), ",\n".join(rgsz)))
    header += ["#endif", ""]
    body += asserts + [""]
    os.makedirs(outdir, exist_ok=True)
    for name, text in (("partids.h", "\n".join(header)), ("parts_tables.c", "\n".join(body))):
        WriteIfChanged(os.path.join(outdir, name), text)


def WriteIfChanged(path, text):
    try:
        with open(path, encoding="ascii", newline="") as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(path, "w", encoding="ascii", newline="") as f:
        f.write(text)


def main(argv):
    if len(argv) != 1 or argv[0].startswith("-"):
        sys.stderr.write(__doc__.split("\n\n")[1] + "\n")
        return 2
    try:
        Generate(argv[0])
    except DataError as e:
        sys.stderr.write("datagen: {}\n".format(e))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
